--All records from products table.
Select * From Products;
--All records from customers table.
Select * From customers;
--Top 5 products
Select Top 5 * from products order by unit_price desc;
--Total number of customers.
Select COUNT(customer_id) from customers;
--Total number of products.
Select COUNT(product_id) from products;
--Total number of orders.
Select COUNT(order_id) from orders;
--Cities where customers reside.
Select distinct City from customers;
--Payment methods
Select distinct payment_method from orders;

--DATA SORTING AND FILTERING
--All products in the Home Appliances category.
Select * from products where category = 'Home Appliances';
--Products with a unit price greater than NGN50,000.
Select product_name, unit_price from products where unit_price > 50000;
--Customers who reside in Lagos.
Select Customer_name from customers where city = 'Lagos';
--All completed orders.
Select * from orders where order_status = 'Completed';
--All cancelled orders.
Select * from orders where order_status = 'Cancelled';
--All orders made in March.
Select * from orders where order_date Between '2026-03-01' and '2026-03-31';
--All products from highest to lowest.
Select * From Products order by unit_price desc;
--Customers names arranged alphabetically.
Select customer_name From customers order by customer_name asc;

--CUSTOMER ANALYSIS
--Numbers of customers in each city.
Select city, COUNT(customer_id) as customers_by_city from customers group by city order by customers_by_city desc;
--City with the highest number of customers.
Select distinct Top 1 city, COUNT(customer_id) as customers_by_city from customers group by city order by customers_by_city desc; 
--Number of orders placed by each customer.
Select customers.customer_name, COUNT (orders.order_id) as Orders_by_each_customer from customers inner join orders on customers.customer_id= orders.customer_id group by customers.customer_name order by Orders_by_each_customer desc;
--Customers who have placed more than one order.
Select customers.customer_name, COUNT (orders.order_id) as Orders_by_each_customer from customers inner join orders on customers.customer_id= orders.customer_id group by customers.customer_name having COUNT(orders.order_id) > 1 order by Orders_by_each_customer desc;
--Customers who have never placed an order.
Select customers.customer_name from customers left join orders on customers.customer_id= orders.customer_id where orders.order_id IS NULL;

--PRODUCT ANALYSIS
--Total quantity sold for each product.
Select products.product_name, sum(order_items.quantity) as Quantity_sold_by_product from products inner join order_items on products.product_id = order_items.product_id group by products.product_name order by Quantity_sold_by_product desc;
--Product with the highest quantity sold.
Select top 1 products.product_name, sum(order_items.quantity) as Quantity_sold_by_product from products inner join order_items on products.product_id = order_items.product_id group by products.product_name order by Quantity_sold_by_product desc;
--Total revenue generated by each product.
Select products.product_name, sum(products.unit_price * order_items.quantity) as Revenue_by_product from products inner join order_items on products.product_id = order_items.product_id inner join orders on order_items.order_id = orders.order_id where orders.order_status = 'Completed' group by products.product_name order by Revenue_by_product desc;
--Product with the highest revenue.
Select top 1 products.product_name, sum(products.unit_price * order_items.quantity) as Revenue_by_product from products inner join order_items on products.product_id = order_items.product_id inner join orders on order_items.order_id = orders.order_id where orders.order_status = 'Completed' group by products.product_name order by Revenue_by_product desc;
--Total reveue generated by each category.
Select products.category, sum(products.unit_price * order_items.quantity) as Revenue_by_product from products inner join order_items on products.product_id = order_items.product_id inner join orders on order_items.order_id = orders.order_id where orders.order_status = 'Completed' group by products.category order by Revenue_by_product desc;
--Category with the highest revenue
Select top 1 products.category, sum(products.unit_price * order_items.quantity) as Revenue_by_product from products inner join order_items on products.product_id = order_items.product_id inner join orders on order_items.order_id = orders.order_id where orders.order_status = 'Completed' group by products.category order by Revenue_by_product desc;
--Average product price.
Select avg(unit_price) from products;
--Products with prices above average product price.
Select product_name, avg(unit_price) from products where unit_price > (select avg(unit_price) from products) group by product_name;

--ORDER ANALYSIS
--Number of orders by payment method.
Select payment_method, count(order_id) as Orders_by_Payment_Method from orders group by payment_method order by Orders_by_Payment_Method desc;
--The most frequently used payment method.
Select top 1 payment_method, count(order_id) as Orders_by_Payment_Method from orders group by payment_method order by Orders_by_Payment_Method desc;
--Orders by status.
Select order_status, count(order_id) as Orders_by_Status from orders group by order_status order by Orders_by_Status desc;
--Total revenue generated from completed orders.
Select orders.order_status, sum (products.unit_price * order_items.quantity) as Total_Revenue_from_Completed_Orders from orders inner join order_items on orders.order_id = order_items.order_id inner join products on order_items.product_id = products.product_id where orders.order_status = 'Completed' group by orders.order_status;
--Total revenue from cancelled orders.
Select orders.order_status, sum (products.unit_price * order_items.quantity) as Total_Revenue_from_Cancelled_Orders from orders inner join order_items on orders.order_id = order_items.order_id inner join products on order_items.product_id = products.product_id where orders.order_status = 'cancelled' group by orders.order_status;
--Average order revenue for completed orders.
With order_totals as (Select orders.order_id, sum (products.unit_price * order_items.quantity) as order_totals  from orders join order_items on orders.order_id = order_items.order_id join products on order_items.product_id = products.product_id where orders.order_status = 'Completed' group by orders.order_id) SELECT AVG(order_totals) AS Avg_Order_Revenue
FROM order_totals;

--CUSTOMER REVENUE ANALYSIS
--Total amount spent by each customer on completed orders.
Select orders.customer_id, sum (products.unit_price * order_items.quantity) as Total_Revenue_from_Completed_Orders from orders inner join order_items on orders.order_id = order_items.order_id inner join products on order_items.product_id = products.product_id where orders.order_status = 'Completed' group by orders.customer_id;
--Customer who spent the most.
Select top 1 orders.customer_id, sum (products.unit_price * order_items.quantity) as Total_Revenue_from_Completed_Orders from orders inner join order_items on orders.order_id = order_items.order_id inner join products on order_items.product_id = products.product_id where orders.order_status = 'Completed' group by orders.customer_id order by Total_Revenue_from_Completed_Orders desc;
--Customers whose total spending exceeded NGN 100000.
Select orders.customer_id,sum(products.unit_price * order_items.quantity) as Customers_Total_Spending from orders inner join order_items on orders.order_id = order_items.order_id inner join products on order_items.product_id = products.product_id where orders.order_status = 'completed' group by orders.customer_id having sum(products.unit_price * order_items.quantity) > 100000;
--Customers total spending by rank.
Select orders.customer_id,sum(products.unit_price * order_items.quantity) as Customers_Total_Spending from orders inner join order_items on orders.order_id = order_items.order_id inner join products on order_items.product_id = products.product_id where orders.order_status = 'completed' group by orders.customer_id having sum(products.unit_price * order_items.quantity) > 100000 order by Customers_Total_Spending desc;
--Top 5 customers by revenue
Select Top 5 orders.customer_id,sum(products.unit_price * order_items.quantity) as Customers_Total_Spending from orders inner join order_items on orders.order_id = order_items.order_id inner join products on order_items.product_id = products.product_id where orders.order_status = 'completed' group by orders.customer_id having sum(products.unit_price * order_items.quantity) > 100000 order by Customers_Total_Spending desc;












